"""Exportable QA summary reports (Markdown and standalone HTML)."""

from __future__ import annotations

import html
from datetime import datetime

from checks import CheckResult, flagged_rows
from explain import get_explainer


def _summary_line(results, n_rows, n_cols, elapsed) -> str:
    passed = sum(1 for r in results if r.passed)
    return (
        f"Checked {n_rows:,} rows x {n_cols} columns in {elapsed:.2f} seconds. "
        f"{passed} of {len(results)} checks passed, "
        f"{len(results) - passed} failed. "
        f"{len(flagged_rows(results))} rows flagged for review."
    )


def build_markdown_report(results: list[CheckResult], source_name: str,
                          n_rows: int, n_cols: int, elapsed: float) -> str:
    explainer = get_explainer()
    lines = [
        "# Data QA Summary",
        "",
        f"**File:** {source_name}  ",
        f"**Generated:** {datetime.now().strftime('%d %b %Y, %H:%M')}  ",
        f"**Result:** {_summary_line(results, n_rows, n_cols, elapsed)}",
        "",
        "Row numbers below are 1-based data rows (row 1 = first row "
        "under the header).",
        "",
        "## Checks",
        "",
    ]
    for result in results:
        status = "PASS" if result.passed else "FAIL"
        lines.append(f"### [{status}] {result.title}")
        lines.append("")
        if result.passed:
            lines.append("No problems found.")
            lines.append("")
            continue
        for finding in result.findings:
            lines.append(f"- {explainer.explain(finding)}")
        lines.append("")
    bad = flagged_rows(results)
    lines += ["## Rows to review", ""]
    if bad:
        lines.append(", ".join(str(r) for r in bad))
    else:
        lines.append("None. The file passed every check.")
    lines.append("")
    lines.append("---")
    lines.append("Generated by Data QA Demo. Explanations are rule-based; "
                 "see README for the LLM plug-in point.")
    return "\n".join(lines)


def build_html_report(results: list[CheckResult], source_name: str,
                      n_rows: int, n_cols: int, elapsed: float) -> str:
    explainer = get_explainer()
    passed = sum(1 for r in results if r.passed)
    cards = []
    for result in results:
        badge = ("<span class='badge pass'>PASS</span>" if result.passed
                 else "<span class='badge fail'>FAIL</span>")
        body = ""
        if result.passed:
            body = "<p class='ok'>No problems found.</p>"
        else:
            items = "".join(
                f"<li>{html.escape(explainer.explain(f))}</li>"
                for f in result.findings)
            body = f"<ul>{items}</ul>"
        cards.append(
            f"<section><h2>{badge} {html.escape(result.title)}</h2>"
            f"{body}</section>")
    bad = flagged_rows(results)
    rows_text = (", ".join(str(r) for r in bad)
                 if bad else "None. The file passed every check.")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Data QA Summary - {html.escape(source_name)}</title>
<style>
  body {{ font-family: -apple-system, 'Segoe UI', Roboto, sans-serif;
         max-width: 860px; margin: 2rem auto; padding: 0 1rem;
         color: #1a1a2e; background: #f7f7fa; }}
  h1 {{ font-size: 1.6rem; margin-bottom: 0.2rem; }}
  .meta {{ color: #555; margin-bottom: 1.5rem; }}
  .stat {{ display: inline-block; background: #fff; border: 1px solid #ddd;
          border-radius: 8px; padding: 0.6rem 1rem; margin: 0 0.4rem 1rem 0; }}
  .stat b {{ font-size: 1.3rem; display: block; }}
  section {{ background: #fff; border: 1px solid #ddd; border-radius: 8px;
            padding: 1rem 1.2rem; margin-bottom: 1rem; }}
  section h2 {{ font-size: 1.1rem; margin: 0 0 0.5rem; }}
  .badge {{ font-size: 0.75rem; padding: 0.15rem 0.5rem; border-radius: 4px;
           color: #fff; vertical-align: middle; }}
  .pass {{ background: #2e7d32; }} .fail {{ background: #c62828; }}
  li {{ margin-bottom: 0.5rem; line-height: 1.45; }}
  .ok {{ color: #2e7d32; }}
  footer {{ color: #777; font-size: 0.85rem; margin-top: 2rem; }}
</style>
</head>
<body>
<h1>Data QA Summary</h1>
<p class="meta">File: <b>{html.escape(source_name)}</b> &middot;
Generated: {datetime.now().strftime('%d %b %Y, %H:%M')}</p>
<div>
  <span class="stat"><b>{n_rows:,}</b>rows</span>
  <span class="stat"><b>{n_cols}</b>columns</span>
  <span class="stat"><b>{elapsed:.2f}s</b>check time</span>
  <span class="stat"><b>{passed}/{len(results)}</b>checks passed</span>
  <span class="stat"><b>{len(bad)}</b>rows flagged</span>
</div>
<p>Row numbers are 1-based data rows (row 1 = first row under the header).</p>
{''.join(cards)}
<section><h2>Rows to review</h2><p>{rows_text}</p></section>
<footer>Generated by Data QA Demo. Explanations are rule-based; see the
project README for the LLM plug-in point.</footer>
</body>
</html>"""
